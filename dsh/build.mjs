#!/usr/bin/env node
// dsh/build.mjs
//
// The build script of the dsh web panel. It writes every artifact under
// `dsh/panel/`, and git tracks each one, so a dsh install runs no build
// step.
//
// Three named targets exist.
//
//   api     esbuild bundles `dsh/src/panel-api-entry.ts` into
//           `dsh/panel/api.js`. The bundle inlines every package and marks
//           the Node built-in modules external.
//   spa     `bun run build:spa:panel` builds the dashboard in `web/`, then
//           this script replaces `dsh/panel/spa/` with the new output.
//   client  esbuild bundles `dsh/src/client.tsx` into
//           `dsh/panel/client.js`. Every module of the frozen dsh module
//           table stays external, and the bundle rides inside the
//           `window.__ModuleLoader__.load` closure.
//
// Usage:
//   node dsh/build.mjs                 build every target
//   node dsh/build.mjs --only=api      build one target
//   node dsh/build.mjs --help
//
// Every run ends with a fresh `dsh/panel/build-info.json`. The stamp reads
// `beastModeVersion` from `.claude-plugin/plugin.json`, which is the single
// source of truth for the version. `dsh/test/packaging.test.js` compares
// the two, so a release that forgets the rebuild fails the test suite.
//
// No person edits a file under `dsh/panel/`. Change the source and run this
// script again.

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = fileURLToPath(new URL('../', import.meta.url));

const WEB_DIR = path.join(REPO_ROOT, 'web');
const PANEL_DIR = path.join(REPO_ROOT, 'dsh', 'panel');
const API_ENTRY = path.join(REPO_ROOT, 'dsh', 'src', 'panel-api-entry.ts');
const API_OUT = path.join(PANEL_DIR, 'api.js');
const CLIENT_ENTRY = path.join(REPO_ROOT, 'dsh', 'src', 'client.tsx');
const CLIENT_OUT = path.join(PANEL_DIR, 'client.js');
const SPA_SOURCE = path.join(WEB_DIR, 'dist', 'spa-panel');
const SPA_OUT = path.join(PANEL_DIR, 'spa');
const BUILD_INFO = path.join(PANEL_DIR, 'build-info.json');
const PLUGIN_MANIFEST = path.join(REPO_ROOT, '.claude-plugin', 'plugin.json');
const WEB_MANIFEST = path.join(WEB_DIR, 'package.json');

/** The target names, in build order. */
const TARGET_NAMES = ['api', 'spa', 'client'];

/**
 * The generated header of `dsh/panel/api.js`. esbuild puts it at the top of
 * the bundle, above every inlined package.
 */
const API_HEADER = `/**
 * GENERATED FILE. Do not edit this file by hand.
 *
 * "dsh/build.mjs" writes this file with the "api" target. It bundles
 * "dsh/src/panel-api-entry.ts", which re-exports createBeastBackend from
 * "web/src/backend/index.ts" and createStaticHandler from
 * "web/src/server/static.ts". The bundle inlines every package, and it
 * marks the Node built-in modules external.
 *
 * To change this file, change the web package source and run
 * "node dsh/build.mjs --only=api" at the repository root.
 */`;

/**
 * The package names the API bundle must never import. `web/src/server/index.ts`
 * imports both, and a build over the wrong entry point pulls them in. The
 * root package declares no runtime dependency, so such an import breaks the
 * panel at request time in a dsh profile.
 */
const FORBIDDEN_PACKAGES = ['hono', '@hono/node-server'];

/**
 * The Node built-in modules the API bundle leaves external. The web backend
 * imports both the bare form ("fs") and the prefixed form ("node:fs"), so
 * the list holds both. `platform: 'node'` already externalizes a builtin,
 * and this explicit list states the contract in one place.
 */
const NODE_BUILTINS = [
  'assert', 'async_hooks', 'buffer', 'child_process', 'cluster', 'console',
  'constants', 'crypto', 'dgram', 'diagnostics_channel', 'dns', 'domain',
  'events', 'fs', 'fs/promises', 'http', 'http2', 'https', 'inspector',
  'module', 'net', 'os', 'path', 'perf_hooks', 'process', 'punycode',
  'querystring', 'readline', 'repl', 'stream', 'stream/promises',
  'string_decoder', 'timers', 'timers/promises', 'tls', 'trace_events',
  'tty', 'url', 'util', 'v8', 'vm', 'worker_threads', 'zlib',
];

const EXTERNALS = [...NODE_BUILTINS, ...NODE_BUILTINS.map((name) => `node:${name}`)];

/**
 * The frozen dsh module table, copied from
 * `packages/client/web/src/platform.ts` of the pinned dsh source, version
 * `0.1.5-rc.1`. The dsh web shell seeds each of these specifiers into its
 * module system, so a client bundle must request them and must never carry
 * its own copy. A second React copy in one page breaks every hook.
 *
 * `react/jsx-dev-runtime` is not a table entry. The list holds it anyway,
 * so a build that switches on the development JSX transform fails at the
 * require check below instead of failing in a browser.
 */
const CLIENT_MODULE_TABLE = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
];

/** The client externals: the module table plus the development JSX runtime. */
const CLIENT_EXTERNALS = [...CLIENT_MODULE_TABLE, 'react/jsx-dev-runtime'];

/**
 * The module id the dsh loader keys the client bundle by. It equals the
 * root package name, which is the id the host writes into the boot graph.
 */
const CLIENT_MODULE_ID = 'beast-mode';

/**
 * The size budget of the client bundle, in bytes. The tab holds one iframe,
 * four notice states, and one message listener, so the bundle stays small.
 * A jump over this line means an accidental inline of a table module.
 */
const CLIENT_MAX_BYTES = 60 * 1024;

// ─────────────────────────────────────────────────────────────────────────
// Output helpers
// ─────────────────────────────────────────────────────────────────────────

function rel(target) {
  return path.relative(REPO_ROOT, target) || '.';
}

function step(message) {
  console.log(`\n━━ ${message}`);
}

function ok(message) {
  console.log(`   ok   ${message}`);
}

function info(message) {
  console.log(`   info ${message}`);
}

/** Print one error line and stop the whole script with exit code 1. */
function fail(message, detail) {
  console.error(`\nERROR: ${message}`);
  if (detail) console.error(String(detail));
  process.exit(1);
}

function formatBytes(bytes) {
  if (bytes === null || bytes === undefined) return 'absent';
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
}

/** Read and parse one JSON file. Stops the script on a bad read or a bad parse. */
function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (error) {
    fail(`cannot read ${rel(file)}`, error);
    return null;
  }
}

/** Sum the bytes of every file under one directory. Returns null when it is absent. */
function directoryBytes(dir) {
  if (!fs.existsSync(dir)) return null;
  let total = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) total += directoryBytes(full) ?? 0;
    else if (entry.isFile()) total += fs.statSync(full).size;
  }
  return total;
}

/** The byte count of one file, or null when the file is absent. */
function fileBytes(file) {
  return fs.existsSync(file) ? fs.statSync(file).size : null;
}

// ─────────────────────────────────────────────────────────────────────────
// The api target
// ─────────────────────────────────────────────────────────────────────────

/**
 * Load esbuild from the root `node_modules`. The import is dynamic, so the
 * spa target still runs in a checkout that holds no root install.
 */
async function loadEsbuild() {
  try {
    return await import('esbuild');
  } catch (error) {
    fail(
      'esbuild is absent. Run "npm install" at the repository root, then run this script again.',
      error,
    );
    return null;
  }
}

/**
 * Collect every bare import specifier of one JavaScript source. A bare
 * specifier names a package, so it does not start with "." or "/".
 *
 * The four patterns cover a static import, a re-export, a dynamic import,
 * and a require call. The scan is a text scan, not a parse, so it can
 * report a specifier that lives inside a string. That direction is safe:
 * the check only ever fails a build that needs a second look.
 *
 * @param {string} code
 * @returns {Set<string>}
 */
function bareImportSpecifiers(code) {
  const patterns = [
    /\bfrom\s*["']([^"']+)["']/g,
    /\bimport\s*\(\s*["']([^"']+)["']\s*\)/g,
    /\brequire\s*\(\s*["']([^"']+)["']\s*\)/g,
    /\bimport\s+["']([^"']+)["']/g,
  ];
  const found = new Set();
  for (const pattern of patterns) {
    for (const match of code.matchAll(pattern)) {
      const specifier = match[1];
      if (specifier.startsWith('.') || specifier.startsWith('/')) continue;
      found.add(specifier);
    }
  }
  return found;
}

/**
 * Assert that the API bundle imports no forbidden package. On a failure the
 * function removes the artifact and stops the script. A removed artifact is
 * the safe state: `dsh/lib/panel.js` logs one line and registers no route,
 * and the dsh boot still succeeds. A broken artifact would instead fail at
 * request time inside a live profile.
 */
function assertNoForbiddenImport(outFile) {
  const code = fs.readFileSync(outFile, 'utf8');
  const bad = [];
  for (const specifier of bareImportSpecifiers(code)) {
    const root = specifier.startsWith('@')
      ? specifier.split('/').slice(0, 2).join('/')
      : specifier.split('/')[0];
    if (FORBIDDEN_PACKAGES.includes(root)) bad.push(specifier);
  }
  if (bad.length > 0) {
    fs.rmSync(outFile, { force: true });
    fail(
      `${rel(outFile)} imports ${bad.join(', ')}. The bundle must hold no server package.\n` +
        'Check that dsh/src/panel-api-entry.ts imports web/src/, never web/dist/. ' +
        `The script removed ${rel(outFile)}.`,
    );
  }
  ok('the bundle imports no hono package');
}

/** Build `dsh/panel/api.js` from `dsh/src/panel-api-entry.ts`. */
async function buildApi() {
  step('api: bundle dsh/src/panel-api-entry.ts');
  if (!fs.existsSync(API_ENTRY)) fail(`${rel(API_ENTRY)} is absent`);

  const esbuild = await loadEsbuild();
  fs.mkdirSync(PANEL_DIR, { recursive: true });

  try {
    await esbuild.build({
      // The dsh build must not read the root tsconfig.json of the Claude Code mod.
      tsconfigRaw: {},
      entryPoints: [API_ENTRY],
      outfile: API_OUT,
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: 'node20',
      // The web package resolves a bare specifier such as "zod" from
      // `web/node_modules`. esbuild walks up from each importer, so the
      // backend files find it on their own. `absWorkingDir` keeps every
      // relative path in a log line stable, and `nodePaths` covers a
      // specifier that reaches esbuild from outside the web tree.
      absWorkingDir: REPO_ROOT,
      nodePaths: [path.join(WEB_DIR, 'node_modules')],
      external: EXTERNALS,
      banner: { js: API_HEADER },
      logLevel: 'warning',
    });
  } catch (error) {
    fail('the esbuild api build failed', error);
  }

  assertNoForbiddenImport(API_OUT);
  ok(`wrote ${rel(API_OUT)} (${formatBytes(fileBytes(API_OUT))})`);
}

// ─────────────────────────────────────────────────────────────────────────
// The spa target
// ─────────────────────────────────────────────────────────────────────────

/** Build the panel SPA in `web/`, then replace `dsh/panel/spa/`. */
function buildSpa() {
  step('spa: build the dashboard at the /beast/ui/ base path');

  const result = spawnSync('bun', ['run', 'build:spa:panel'], {
    cwd: WEB_DIR,
    stdio: 'inherit',
  });

  if (result.error && result.error.code === 'ENOENT') {
    fail('bun is absent. The web package builds with bun and vite. Install bun, then run this script again.');
  }
  if (result.error) fail('the spa build failed to start', result.error);
  if (result.status !== 0) fail(`"bun run build:spa:panel" exited with code ${result.status}`);

  const indexFile = path.join(SPA_SOURCE, 'index.html');
  if (!fs.existsSync(indexFile)) fail(`the spa build wrote no ${rel(indexFile)}`);

  // Remove the old directory before the copy, so an asset the new build
  // dropped never survives in the artifact.
  fs.rmSync(SPA_OUT, { recursive: true, force: true });
  fs.mkdirSync(PANEL_DIR, { recursive: true });
  fs.cpSync(SPA_SOURCE, SPA_OUT, { recursive: true });

  const html = fs.readFileSync(path.join(SPA_OUT, 'index.html'), 'utf8');
  if (!html.includes('/beast/ui/')) {
    fail(
      `${rel(path.join(SPA_OUT, 'index.html'))} names no asset under /beast/ui/. ` +
        'Check the --base flag of the build:spa:panel script in web/package.json.',
    );
  }
  ok('the index page names an asset under /beast/ui/');
  ok(`wrote ${rel(SPA_OUT)} (${formatBytes(directoryBytes(SPA_OUT))})`);
}

// ─────────────────────────────────────────────────────────────────────────
// The client target
// ─────────────────────────────────────────────────────────────────────────

/**
 * The generated header of `dsh/panel/client.js`. The wrapper below puts it
 * inside the loader closure, so the first line of the file stays the
 * `window.__ModuleLoader__.load({` call that the dsh boot queue reads.
 */
const CLIENT_HEADER = `/**
 * GENERATED FILE. Do not edit this file by hand.
 *
 * "dsh/build.mjs" writes this file with the "client" target. It bundles
 * "dsh/src/client.tsx", the Beast Mode panel plugin of the dsh web UI.
 * Every module of the frozen dsh module table stays external, so this
 * bundle carries no second copy of React.
 *
 * To change this file, change "dsh/src/client.tsx" and run
 * "node dsh/build.mjs --only=client" at the repository root.
 */`;

/**
 * Wrap one CJS bundle in the dsh client-bundle closure.
 *
 * The dsh boot queue reads `window.__ModuleLoader__.load({ id, factory })`
 * (`packages/client/modules/src/index.ts`). The factory receives the host
 * `require`, which answers every module-table specifier, and it returns the
 * module exports. The reference bundle at
 * `<profile>/node_modules/dshmarket/client/client.js` carries the same
 * shape.
 * @param {string} bundle - the esbuild CJS output.
 * @returns {string} the whole artifact text.
 */
function wrapClientBundle(bundle) {
  return `window.__ModuleLoader__.load({ id: ${JSON.stringify(CLIENT_MODULE_ID)}, factory: (require) => {
${CLIENT_HEADER}
	var module = { exports: {} };
	var exports = module.exports;
${bundle}
	return module.exports;
} });
`;
}

/**
 * Collect every `require("...")` specifier of one bundle.
 * @param {string} code
 * @returns {string[]} the sorted, unique specifiers.
 */
function requiredSpecifiers(code) {
  const found = new Set();
  for (const match of code.matchAll(/\brequire\s*\(\s*["']([^"']+)["']\s*\)/g)) {
    found.add(match[1]);
  }
  return [...found].sort();
}

/**
 * Assert that the client bundle requests module-table specifiers only.
 *
 * A specifier outside the table never resolves in the browser, because the
 * dsh module system answers a seed module, an arrived package row, or
 * nothing. On a failure the function removes the artifact and stops the
 * script, which is the safe state: a dsh profile that finds no `client.js`
 * reports one clear `MissingClientBundleError` instead of a broken tab.
 * @param {string} code - the wrapped artifact text.
 * @param {string} outFile - the artifact path, removed on a failure.
 */
function assertClientExternals(code, outFile) {
  const specifiers = requiredSpecifiers(code);
  const bad = specifiers.filter((specifier) => !CLIENT_MODULE_TABLE.includes(specifier));
  if (bad.length > 0) {
    fs.rmSync(outFile, { force: true });
    fail(
      `${rel(outFile)} requests ${bad.join(', ')}, which the dsh module table does not hold.\n`
        + 'Import a module-table entry only, or add the specifier to CLIENT_MODULE_TABLE after '
        + `you confirm it in packages/client/web/src/platform.ts. The script removed ${rel(outFile)}.`,
    );
  }
  ok(`the bundle requests module-table entries only: ${specifiers.join(', ')}`);
}

/** Build `dsh/panel/client.js` from `dsh/src/client.tsx`. */
async function buildClient() {
  step('client: bundle dsh/src/client.tsx');
  if (!fs.existsSync(CLIENT_ENTRY)) fail(`${rel(CLIENT_ENTRY)} is absent`);

  const esbuild = await loadEsbuild();
  fs.mkdirSync(PANEL_DIR, { recursive: true });

  let bundle = '';
  try {
    const result = await esbuild.build({
      entryPoints: [CLIENT_ENTRY],
      // The dsh build must not read the root tsconfig.json of the Claude Code mod.
      tsconfigRaw: {},
      bundle: true,
      platform: 'browser',
      format: 'cjs',
      target: 'es2022',
      // The automatic transform emits `react/jsx-runtime`, a table entry.
      // `jsxDev` stays off, so no build ever reaches `react/jsx-dev-runtime`.
      jsx: 'automatic',
      jsxDev: false,
      absWorkingDir: REPO_ROOT,
      external: CLIENT_EXTERNALS,
      // The wrapper owns the file text, so esbuild returns the bytes instead
      // of writing them.
      write: false,
      logLevel: 'warning',
    });
    bundle = result.outputFiles[0].text;
  } catch (error) {
    fail('the esbuild client build failed', error);
  }

  fs.writeFileSync(CLIENT_OUT, wrapClientBundle(bundle));

  const code = fs.readFileSync(CLIENT_OUT, 'utf8');
  if (!code.startsWith('window.__ModuleLoader__.load({')) {
    fs.rmSync(CLIENT_OUT, { force: true });
    fail(`${rel(CLIENT_OUT)} must start with the dsh module-loader call`);
  }
  assertClientExternals(code, CLIENT_OUT);

  const bytes = fileBytes(CLIENT_OUT);
  if (bytes > CLIENT_MAX_BYTES) {
    fail(
      `${rel(CLIENT_OUT)} is ${formatBytes(bytes)}, over the ${formatBytes(CLIENT_MAX_BYTES)} budget. `
        + 'Check that every module-table entry is still external.',
    );
  }
  ok(`the bundle is inside the ${formatBytes(CLIENT_MAX_BYTES)} budget`);
  ok(`wrote ${rel(CLIENT_OUT)} (${formatBytes(bytes)})`);
}

// ─────────────────────────────────────────────────────────────────────────
// The stamp
// ─────────────────────────────────────────────────────────────────────────

/**
 * Write `dsh/panel/build-info.json`.
 *
 * The function reads every artifact from disk, so the stamp stays true
 * after a single-target run. `beastModeVersion` comes from
 * `.claude-plugin/plugin.json` and never from the root `package.json`.
 * The plugin manifest is the single source of truth for the version.
 */
function writeBuildInfo() {
  step('stamp: write dsh/panel/build-info.json');
  const beastModeVersion = readJson(PLUGIN_MANIFEST).version;
  const webVersion = readJson(WEB_MANIFEST).version;

  const stamp = {
    beastModeVersion,
    webVersion,
    built: new Date().toISOString(),
    artifacts: {
      'api.js': fileBytes(API_OUT),
      spa: directoryBytes(SPA_OUT),
      'client.js': fileBytes(CLIENT_OUT),
    },
  };

  fs.mkdirSync(PANEL_DIR, { recursive: true });
  fs.writeFileSync(BUILD_INFO, `${JSON.stringify(stamp, null, 2)}\n`);
  ok(`beastModeVersion ${beastModeVersion}, webVersion ${webVersion}`);
  for (const [name, bytes] of Object.entries(stamp.artifacts)) {
    ok(`${name}: ${bytes === null ? 'absent' : formatBytes(bytes)}`);
  }
}

// ─────────────────────────────────────────────────────────────────────────
// The command line
// ─────────────────────────────────────────────────────────────────────────

const HELP_TEXT = `
node dsh/build.mjs [--only=<target>]

  --only=<target>   Build one target. The targets are api, spa, and client.
  --help            Print this text.

Every run writes dsh/panel/build-info.json.
`.trim();

function parseArgs(argv) {
  let only = null;
  for (const arg of argv) {
    if (arg === '--help' || arg === '-h') return { help: true, only: null };
    if (arg.startsWith('--only=')) {
      only = arg.slice('--only='.length);
      continue;
    }
    fail(`unknown argument "${arg}"\n\n${HELP_TEXT}`);
  }
  if (only !== null && !TARGET_NAMES.includes(only)) {
    fail(`unknown target "${only}". The targets are ${TARGET_NAMES.join(', ')}.`);
  }
  return { help: false, only };
}

async function main(argv) {
  const { help, only } = parseArgs(argv);
  if (help) {
    console.log(HELP_TEXT);
    return;
  }

  const selected = only === null ? TARGET_NAMES : [only];
  console.log(`Beast Mode dsh panel build: ${selected.join(', ')}`);

  for (const target of selected) {
    if (target === 'api') await buildApi();
    if (target === 'spa') buildSpa();
    if (target === 'client') await buildClient();
  }

  writeBuildInfo();
  console.log('\nThe build finished.');
}

await main(process.argv.slice(2));
