// dsh/test/packaging.test.js
//
// Covers the packaging contract of implementation.md section 3.8
// (harness-support/dsh-web-panel, Phase 3): the three `exports` entries of
// the root package.json, the `dsh.client` declaration, the absent
// `dependencies` key, and the build artifacts under `dsh/panel/`.
//
// It also holds the three-way version parity of the orca-plugin contract
// (Q6, A8): `package.json`, `.claude-plugin/plugin.json`, and
// `orca/orca-plugin.json` carry one version, and a release edits all three
// fields.
//
// Every test runs with plain Node. No test runs a build, no test starts
// dsh, and no test opens a socket. An artifact test skips with a clear
// message when `dsh/panel/` is absent, so a fresh clone that ran no build
// still passes the suite.

import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import vm from 'node:vm';

const REPO_ROOT = fileURLToPath(new URL('../../', import.meta.url));
const PANEL_DIR = path.join(REPO_ROOT, 'dsh', 'panel');
const CLIENT_ARTIFACT = path.join(PANEL_DIR, 'client.js');
const BUILD_INFO = path.join(PANEL_DIR, 'build-info.json');
const SPA_INDEX = path.join(PANEL_DIR, 'spa', 'index.html');

/**
 * The three version fields a release must bump together (Q6, A8), in the
 * order the parity test names them in its message.
 */
const PARITY_FILES = ['package.json', '.claude-plugin/plugin.json', 'orca/orca-plugin.json'];

/** The three `exports` entries of section 3.8, in one place. */
const EXPECTED_EXPORTS = {
  './client': './dsh/panel/client.js',
  './cordis.patch.yml': './dsh/cordis.patch.yml',
  './package.json': './package.json',
};

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(REPO_ROOT, relativePath), 'utf8'));
}

const rootPackage = readJson('package.json');

/**
 * The skip reason for every artifact test, or false when the artifacts are
 * present. `node dsh/build.mjs` writes them, and git tracks each one, so a
 * normal checkout runs every test.
 */
const PANEL_SKIP = fs.existsSync(PANEL_DIR)
  ? false
  : 'dsh/panel/ is absent. Run "node dsh/build.mjs" at the repository root to write the artifacts.';

/** The frozen dsh module table, per `packages/client/web/src/platform.ts`. */
const CLIENT_MODULE_TABLE = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
];

/** The size budget of the client bundle, in bytes, per implementation.md section 4. */
const CLIENT_MAX_BYTES = 60 * 1024;

test('the root package.json declares the three exports entries', () => {
  assert.ok(rootPackage.exports, 'the root package.json must declare an exports map');
  assert.deepEqual(rootPackage.exports, EXPECTED_EXPORTS);
});

test('every exports target that is not a build artifact exists on disk', () => {
  for (const [subpath, target] of Object.entries(EXPECTED_EXPORTS)) {
    if (subpath === './client') continue;
    const file = path.join(REPO_ROOT, target);
    assert.ok(fs.existsSync(file), `the exports entry "${subpath}" names a missing file: ${target}`);
    assert.ok(fs.statSync(file).isFile(), `the exports entry "${subpath}" must name a file`);
  }
});

test('the ./client exports target exists on disk', { skip: PANEL_SKIP }, () => {
  assert.ok(
    fs.existsSync(CLIENT_ARTIFACT),
    'dsh/panel/client.js must exist. dsh throws MissingClientBundleError for a declared '
      + 'dsh.client whose "./client" target is absent. Run "node dsh/build.mjs --only=client".',
  );
  assert.ok(fs.statSync(CLIENT_ARTIFACT).isFile(), 'the ./client export must name a file');
});

test('the client bundle rides inside the dsh module-loader closure', { skip: PANEL_SKIP }, () => {
  const code = fs.readFileSync(CLIENT_ARTIFACT, 'utf8');
  assert.ok(
    code.startsWith('window.__ModuleLoader__.load({'),
    'the dsh boot queue reads window.__ModuleLoader__.load({ id, factory }) as the first statement',
  );
  assert.match(code, /id: "beast-mode"/, 'the module id must equal the root package name');
  assert.match(code, /GENERATED FILE\. Do not edit this file by hand\./);
  assert.match(code, /dsh\/build\.mjs/);
});

test('the client factory returns the three plugin exports', { skip: PANEL_SKIP }, () => {
  const code = fs.readFileSync(CLIENT_ARTIFACT, 'utf8');

  // Evaluate the artifact against a fake module loader and a fake module
  // table. The test proves the loader shape with no browser and no dsh: the
  // file registers one bundle, and its factory returns the plugin face that
  // Cordis reads.
  let registered = null;
  const context = vm.createContext({
    window: { __ModuleLoader__: { load(spec) { registered = spec; } } },
    console,
  });
  vm.runInContext(code, context, { filename: 'dsh/panel/client.js' });

  assert.ok(registered !== null, 'the artifact must call window.__ModuleLoader__.load once');
  assert.equal(registered.id, 'beast-mode');
  assert.equal(typeof registered.factory, 'function');

  const requested = [];
  const stub = new Proxy({}, { get: () => () => undefined });
  const exported = registered.factory((specifier) => {
    requested.push(specifier);
    assert.ok(
      CLIENT_MODULE_TABLE.includes(specifier),
      `the factory requested "${specifier}", which the frozen dsh module table does not hold`,
    );
    return stub;
  });

  assert.equal(exported.name, 'beast-mode-panel');
  // The spread copies the array out of the vm realm, where its prototype
  // differs from the test realm's Array prototype.
  assert.deepEqual([...exported.inject], ['slots', 'sessions', 'workspaces']);
  assert.equal(typeof exported.apply, 'function');
  assert.ok(requested.includes('react'), 'the factory must request react from the host');
});

test('the client bundle requests module-table specifiers only', { skip: PANEL_SKIP }, () => {
  const code = fs.readFileSync(CLIENT_ARTIFACT, 'utf8');
  const requested = [...code.matchAll(/\brequire\s*\(\s*"([^"]+)"\s*\)/g)].map((match) => match[1]);
  assert.ok(requested.includes('react'), 'the client bundle must request react from the host');
  for (const specifier of new Set(requested)) {
    assert.ok(
      CLIENT_MODULE_TABLE.includes(specifier),
      `the client bundle requests "${specifier}", which the frozen dsh module table does not hold`,
    );
  }
});

test('the client bundle stays inside its size budget', { skip: PANEL_SKIP }, () => {
  const bytes = fs.statSync(CLIENT_ARTIFACT).size;
  assert.ok(
    bytes < CLIENT_MAX_BYTES,
    `dsh/panel/client.js is ${String(bytes)} bytes, over the ${String(CLIENT_MAX_BYTES)} byte budget. `
      + 'A jump means a module-table entry became an inlined copy.',
  );
});

test('dsh.client declares the web platform and no package row injection', () => {
  const client = rootPackage.dsh?.client;
  assert.ok(client, 'the root package.json must declare dsh.client');
  assert.equal(client.platform, 'web');
  // dsh.client.inject names package rows whose factories must load first, not
  // Cordis services (packages/client/modules/src/client/manifest.ts:45-58).
  // The Beast Mode client bundle asks only for react and react/jsx-runtime
  // from the baseline module table, so it needs no package row here.
  assert.ok(
    client.inject === undefined || (Array.isArray(client.inject) && client.inject.length === 0),
    'dsh.client.inject must be absent or an empty array, because the bundle needs no package row',
  );
});

test('the files array ships dsh/ and drops the build inputs and the tests', () => {
  // `npm pack --dry-run` proves the behavior. This test pins the manifest
  // shape, because npm reads the list in order: the `dsh/` entry adds the
  // whole directory, and each negation below it takes one subdirectory back
  // out. A negation above `dsh/` would do nothing.
  const files = rootPackage.files ?? [];
  const directory = files.indexOf('dsh/');
  assert.ok(directory >= 0, 'the files array must ship the dsh/ directory');
  for (const negation of ['!dsh/src/', '!dsh/test/']) {
    const at = files.indexOf(negation);
    assert.ok(at >= 0, `the files array must hold the negation entry ${negation}`);
    assert.ok(at > directory, `${negation} must come after the "dsh/" entry`);
  }
});

test('the root package.json declares no runtime dependency', () => {
  const dependencies = rootPackage.dependencies ?? {};
  assert.deepEqual(
    Object.keys(dependencies),
    [],
    'the root package ships plain source with zero runtime dependencies',
  );
});

test('the dsh bundle patch entry still names the cordis patch file', () => {
  assert.equal(rootPackage.dsh?.bundle?.patch, './dsh/cordis.patch.yml');
});

test('the build stamp version equals the plugin manifest version', { skip: PANEL_SKIP }, () => {
  assert.ok(fs.existsSync(BUILD_INFO), 'dsh/panel/build-info.json must exist beside the artifacts');
  const stamp = JSON.parse(fs.readFileSync(BUILD_INFO, 'utf8'));
  const pluginVersion = readJson('.claude-plugin/plugin.json').version;
  assert.equal(
    stamp.beastModeVersion,
    pluginVersion,
    'the artifacts are stale. Run "node dsh/build.mjs" after a version bump.',
  );
});

test('package.json, the plugin manifest, and the Orca manifest hold one version', () => {
  // No skip path on purpose (Q6, A8): a release now edits three version fields,
  // not two, so a missing orca/orca-plugin.json is a release that missed the
  // third bump. Silence here would let the next release forget it too.
  const orcaManifest = PARITY_FILES[2];
  assert.ok(
    fs.existsSync(path.join(REPO_ROOT, orcaManifest)),
    `${orcaManifest} is missing. A release edits three version fields, not two: `
      + `${PARITY_FILES.join(', ')}. The absent file is the one whose bump went missed.`,
  );

  const versions = PARITY_FILES.map((file) => ({ file, version: readJson(file).version }));
  if (new Set(versions.map((entry) => entry.version)).size === 1) return;

  // With three fields a disagreement is a 2-to-1 split: the file whose value
  // stands alone is the one the release forgot to bump.
  const counts = new Map();
  for (const { version } of versions) counts.set(version, (counts.get(version) ?? 0) + 1);
  const [majority] = [...counts.entries()].sort((a, b) => b[1] - a[1])[0];
  const laggards = versions.filter((entry) => entry.version !== majority);
  assert.fail(
    'version parity broke: '
      + `${laggards.map((entry) => `${entry.file} = ${entry.version}`).join(', ')} `
      + `disagrees with the ${String(majority)} carried by the rest. `
      + `A release edits three version fields, not two: ${PARITY_FILES.join(', ')}. `
      + `Bump ${laggards.map((entry) => entry.file).join(' and ')} in the same commit.`,
  );
});

test('the build stamp records the web version and the build time', { skip: PANEL_SKIP }, () => {
  const stamp = JSON.parse(fs.readFileSync(BUILD_INFO, 'utf8'));
  assert.equal(stamp.webVersion, readJson('web/package.json').version);
  assert.ok(!Number.isNaN(Date.parse(stamp.built)), 'build-info.json "built" must be an ISO timestamp');
  assert.ok(stamp.artifacts, 'build-info.json must record one byte count per artifact');
});

